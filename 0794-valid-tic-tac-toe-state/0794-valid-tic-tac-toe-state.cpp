class Solution {
public:
    inline const bool validTicTacToe(
        const vector<string>& __b
    ) const noexcept {
        char __o =
            ( __b[0] == "OOO" ) +
            ( __b[1] == "OOO" ) +
            ( __b[2] == "OOO" ) +
            ( __b[0][0] == 'O' && __b[0][0] == __b[1][0] && __b[0][0] == __b[2][0] ) +
            ( __b[0][1] == 'O' && __b[0][1] == __b[1][1] && __b[0][1] == __b[2][1] ) +
            ( __b[0][2] == 'O' && __b[0][2] == __b[1][2] && __b[0][2] == __b[2][2] ) +
            ( __b[0][0] == 'O' && __b[0][0] == __b[1][1] && __b[0][0] == __b[2][2] ) +
            ( __b[0][2] == 'O' && __b[0][2] == __b[1][1] && __b[0][2] == __b[2][0] );

        char __x =
            ( __b[0] == "XXX" ) +
            ( __b[1] == "XXX" ) +
            ( __b[2] == "XXX" ) +
            ( __b[0][0] == 'X' && __b[0][0] == __b[1][0] && __b[0][0] == __b[2][0] ) +
            ( __b[0][1] == 'X' && __b[0][1] == __b[1][1] && __b[0][1] == __b[2][1] ) +
            ( __b[0][2] == 'X' && __b[0][2] == __b[1][2] && __b[0][2] == __b[2][2] ) +
            ( __b[0][0] == 'X' && __b[0][0] == __b[1][1] && __b[0][0] == __b[2][2] ) +
            ( __b[0][2] == 'X' && __b[0][2] == __b[1][1] && __b[0][2] == __b[2][0] );

        if( __o && __x || __x > 2 || __o > 2 ) return 0;
        else if( __x ) {
            __o = 0;
            __x = 0;

            for( char __i{}; __i < 3; ++__i )
                for( char __j{}; __j < 3; ++__j )
                    if( __b[__i][__j] == 'X' ) ++__x;
                    else if( __b[__i][__j] == 'O' ) ++__o;

            if( __x == __o ) return 0;

        }
        else if( __o ) {
            __o = 0;
            __x = 0;

            for( char __i{}; __i < 3; ++__i )
                for( char __j{}; __j < 3; ++__j )
                    if( __b[__i][__j] == 'X' ) ++__x;
                    else if( __b[__i][__j] == 'O' ) ++__o;

            if( __o < __x ) return 0;

        }

        __o = 0;
        __x = 0;

        for( char __i{}; __i < 3; ++__i )
            for( char __j{}; __j < 3; ++__j )
                if( __b[__i][__j] == 'X' ) ++__x;
                else if( __b[__i][__j] == 'O' ) ++__o;

        if( __o > __x || __x - __o > 1 ) return 0;

        return 1;
        
    }
};

